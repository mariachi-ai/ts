#!/usr/bin/env node
// Generates packages/core/docs/llms.txt, the index of the docs for coding agents, from the index in
// packages/core/docs/README.md. `--check` fails if the file is stale, or if a doc is in the folder
// and not in the index (CI). `mariachi docs` reads the file.
import fs from 'node:fs';
import path from 'node:path';

const DOCS = 'packages/core/docs';
const OUT = `${DOCS}/llms.txt`;
const errors = [];

const readme = fs.readFileSync(`${DOCS}/README.md`, 'utf8');
const lines = readme.split('\n');

/** The first paragraph after the title, on one line. */
function firstParagraph(text) {
  const body = text.split('\n').slice(1);
  const start = body.findIndex((line) => line.trim() && !line.startsWith('#') && !line.startsWith('<!--'));
  if (start === -1) return '';
  const end = body.findIndex((line, i) => i > start && !line.trim());
  return body
    .slice(start, end === -1 ? undefined : end)
    .join(' ')
    .replace(/\s+/g, ' ')
    .trim();
}

/** A doc's own first sentence, for an index line that gives no description. */
function ownSummary(file) {
  const paragraph = firstParagraph(fs.readFileSync(path.join(DOCS, file), 'utf8')).replace(/\[([^\]]+)\]\([^)]+\)/g, '$1');
  const sentence = /^(.+?[.:])(\s|$)/.exec(paragraph)?.[1] ?? paragraph;
  return sentence.replace(/[.:]$/, '');
}

const sections = [];
const listed = new Set();
let current;
for (const line of lines) {
  const heading = /^## (.+)$/.exec(line);
  if (heading) {
    current = { title: heading[1].trim(), entries: [] };
    sections.push(current);
    continue;
  }
  if (!current || !/^\s*(-|\d+\.) /.test(line)) continue;
  const links = [...line.matchAll(/\[[^\]]*\]\(\.\/([^)\s#]+\.md)\)/g)].map((m) => m[1]);
  if (links.length === 0) continue;
  // What follows the last link's colon describes the line; with several links on a line, each gets its own
  const described = links.length === 1 ? /\)\s*:\s*(.+)$/.exec(line)?.[1]?.trim() : undefined;
  for (const file of links) {
    if (!fs.existsSync(path.join(DOCS, file))) {
      errors.push(`README.md lists ${file}, which is not there`);
      continue;
    }
    if (listed.has(file)) continue;
    listed.add(file);
    const summary = (described ?? ownSummary(file)).replace(/\[([^\]]+)\]\([^)]+\)/g, '$1');
    current.entries.push({ name: file.replace(/\.md$/, ''), file, summary });
  }
}

function collect(dir) {
  return fs.readdirSync(path.join(DOCS, dir), { withFileTypes: true }).flatMap((entry) => {
    const rel = path.posix.join(dir, entry.name);
    if (entry.isDirectory()) return collect(rel);
    return entry.name.endsWith('.md') ? [rel] : [];
  });
}
for (const file of collect('.')) {
  if (file !== 'README.md' && !listed.has(file)) errors.push(`${file} is not in the index in ${DOCS}/README.md: add a line for it`);
}

const out = [
  '# Mariachi',
  '',
  `> ${firstParagraph(readme)}`,
  '',
  'These are the framework\'s docs, which ship inside `@mariachi/core` (`node_modules/@mariachi/core/docs/`).',
  'Paths are relative to that folder. `mariachi docs` lists them, `mariachi docs <name>` prints one,',
  '`mariachi docs <name> --section <heading>` prints one section, and `mariachi docs --search <words>`',
  'finds the lines that have every word.',
  '',
  '<!-- Generated by `pnpm docs:catalog` from the index in README.md. Do not edit. -->',
  '',
];
for (const section of sections) {
  if (section.entries.length === 0) continue;
  out.push(`## ${section.title}`, '');
  for (const entry of section.entries) out.push(`- [${entry.name}](./${entry.file}): ${entry.summary}`);
  out.push('');
}
const content = out.join('\n');
const count = sections.reduce((n, s) => n + s.entries.length, 0);

if (errors.length > 0) {
  for (const e of errors) console.error(`llms.txt: ${e}`);
  process.exit(1);
}
if (process.argv.includes('--check')) {
  const existing = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
  if (existing !== content) {
    console.error(`${OUT} is stale; run pnpm docs:catalog`);
    process.exit(1);
  }
  console.log(`${OUT} is up to date (${count} docs).`);
} else {
  fs.writeFileSync(OUT, content);
  console.log(`Wrote ${OUT} (${count} docs).`);
}
