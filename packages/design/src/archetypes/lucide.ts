/** An inline Lucide icon at a size and stroke, in the current text colour. */
export function lucideSvg(name: string, size: number, stroke: number, label?: string): string {
  const paths = lucidePaths[name];
  if (!paths) throw new DesignError('design/missing-asset', `No Lucide path for "${name}"`);
  const a11y = label ? ` role="img" aria-label="${label}"` : ' aria-hidden="true"';
  return `<svg width="${size}" height="${size}" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="${stroke}" stroke-linecap="round" stroke-linejoin="round"${a11y}>${paths}</svg>`;
}
