#!/usr/bin/env node
// Showcases (src/showcase/): someone's key component drawn in every design language.
//
//   pnpm --filter @mariachi/design showcase                       write dist/showcase/: each kind in each language,
//                                                                 light and dark, and index.html, a gallery of all
//   pnpm --filter @mariachi/design showcase --arrangements [dir]  regenerate src/showcase/arrangements.ts from the
//                                                                 measured screens in dir (default .fingerprints/,
//                                                                 written by `fingerprint`); then rebuild
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const dist = path.join(root, 'dist');
const args = process.argv.slice(2);

if (args[0] === '--arrangements') {
  const { arrangementsFrom, buildFingerprint } = await import('../dist/build.js');
  const dir = path.resolve(args[1] ?? path.join(root, '.fingerprints'));
  const fps = fs
    .readdirSync(dir)
    .filter((f) => f.endsWith('.screens.json'))
    .sort()
    .map((f) =>
      buildFingerprint(f.replace('.screens.json', ''), JSON.parse(fs.readFileSync(path.join(dir, f), 'utf8')), {
        mode: 'language',
        measuredAt: '',
      }),
    );
  if (fps.length < 3)
    throw new Error(
      `Arrangements are relative to the other languages: ${dir} has ${fps.length} measured, need all of them`,
    );
  const arr = arrangementsFrom(fps);
  const body = Object.keys(arr)
    .sort()
    .map(
      (id) =>
        `  ${/^[a-z]+$/.test(id) ? id : `'${id}'`}: ${JSON.stringify(arr[id])
          .replace(/"([a-z]+)":/g, '$1: ')
          .replace(/"/g, "'")
          .replace(/,/g, ', ')},`,
    )
    .join('\n');
  fs.writeFileSync(
    path.join(root, 'src/showcase/arrangements.ts'),
    `// Generated by \`pnpm --filter @mariachi/design showcase --arrangements\` from the languages' fingerprints. Do not edit.\nimport type { Arrangement } from './types';\n\nexport const arrangements: Record<string, Arrangement> = {\n${body}\n};\n`,
  );
  console.log(`${fps.length} arrangements written to src/showcase/arrangements.ts`);
  process.exit(0);
}

const { archetypes, arrangementOf, drawShowcase, drawnKinds } = await import('../dist/index.js');
const out = path.join(dist, 'showcase');
fs.mkdirSync(out, { recursive: true });
const page = (
  a,
  kind,
  mode,
) => `<!doctype html><html lang="en" data-theme="${a.id}" data-mode="${mode}"><head><meta charset="utf-8"><title>${a.id} · ${kind}</title>
<link rel="stylesheet" href="../kits/${a.id}/index.css"><link rel="stylesheet" href="../css/mariachi.css">
<style>html,body{background:var(--m-color-bg-canvas);color:var(--m-color-fg-default)}body{margin:0;padding:var(--m-space-5)}svg{flex-shrink:0}</style>
</head><body>${drawShowcase(kind, a)}</body></html>`;
for (const kind of drawnKinds) {
  for (const a of archetypes)
    for (const mode of ['light', 'dark'])
      fs.writeFileSync(path.join(out, `${kind}-${a.id}-${mode}.html`), page(a, kind, mode));
}
const tile = (a, kind, mode) => {
  const r = arrangementOf(a);
  return `<figure><iframe src="${kind}-${a.id}-${mode}.html" loading="lazy" title="${a.id}"></iframe><figcaption><b>${a.id}</b> ${r.separation} · ${r.media} · ${r.title} · ${r.density} · ${r.primary} · ${r.width}</figcaption></figure>`;
};
const mode = (a) => (a.tags.mode === 'dark-first' ? 'dark' : 'light');
fs.writeFileSync(
  path.join(out, 'index.html'),
  `<!doctype html><html lang="en"><head><meta charset="utf-8"><title>Showcases</title><style>
body{font:13px system-ui;margin:24px;background:#f4f4f5}h2{margin:32px 0 12px}
.grid{display:grid;grid-template-columns:repeat(auto-fill,minmax(380px,1fr));gap:16px}
figure{margin:0;background:#fff;border:1px solid #e4e4e7;border-radius:8px;overflow:hidden}
iframe{display:block;width:100%;height:520px;border:0}figcaption{padding:6px 10px;color:#52525b;border-top:1px solid #e4e4e7}
</style></head><body>${drawnKinds.map((k) => `<h2 id="${k}">${k}</h2><div class="grid">${archetypes.map((a) => tile(a, k, mode(a))).join('')}</div>`).join('')}</body></html>`,
);
console.log(`dist/showcase/: ${drawnKinds.length} kinds × ${archetypes.length} languages × 2 modes, and index.html`);
